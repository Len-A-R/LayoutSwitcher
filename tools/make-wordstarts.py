# Generates uWordStarts.pas: the first 3 and 4 letters of the words of the
# Russian and English Hunspell dictionaries (LibreOffice dictionaries:
# ru_RU by Alexander I. Lebedev, BSD; en_US from SCOWL).  Only these letter
# combinations are stored, not the dictionaries.
#
#   python tools/make-wordstarts.py [folder with ru_RU.* and en_US.*]
#
# Without a folder the dictionaries are downloaded into a temporary folder.

import os
import re
import sys
import tempfile
import urllib.request

BASE = 'https://raw.githubusercontent.com/LibreOffice/dictionaries/master/'
FILES = {'ru_RU': 'ru_RU/ru_RU', 'en_US': 'en/en_US'}
ALPHABET = {
    'ru_RU': set('абвгдежзийклмнопрстуфхцчшщъыьэюя'),
    'en_US': set('abcdefghijklmnopqrstuvwxyz'),
}
PER_LINE = 60  # n-grams per string literal (Delphi limits a literal to 255 chars)


def fetch(folder):
    for name, path in FILES.items():
        for ext in ('.dic', '.aff'):
            target = os.path.join(folder, name + ext)
            if not os.path.exists(target):
                urllib.request.urlretrieve(BASE + path + ext, target)


def read_words(folder, name):
    prefixes = {}
    with open(os.path.join(folder, name + '.aff'), encoding='utf-8') as aff:
        for line in aff:
            parts = line.split()
            # "PFX <flag> <strip> <add> <condition>"; header lines have Y/N.
            if len(parts) >= 4 and parts[0] == 'PFX' and parts[2] not in ('Y', 'N'):
                if parts[2] == '0':
                    prefixes.setdefault(parts[1], []).append(parts[3])
    with open(os.path.join(folder, name + '.dic'), encoding='utf-8') as dic:
        lines = dic.read().split('\n')[1:]
    for line in lines:
        word, _, flags = line.strip().partition('/')
        if not word:
            continue
        word = word.lower().replace('ё', 'е')
        yield word
        for flag in flags:
            for prefix in prefixes.get(flag, ()):
                yield prefix + word


def starts(words, length, alphabet):
    return sorted({w[:length] for w in words
                   if len(w) >= length and all(c in alphabet for c in w[:length])})


def pascal_array(name, items):
    rows = [''.join(items[i:i + PER_LINE]) for i in range(0, len(items), PER_LINE)]
    body = ',\r\n'.join("    '%s'" % row for row in rows)
    return '  %s: array[0..%d] of string = (\r\n%s);\r\n' % (name, len(rows) - 1, body)


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp(prefix='ls-dicts-')
    fetch(folder)
    sets = {}
    for name in FILES:
        words = list(read_words(folder, name))
        for length in (3, 4):
            sets[name, length] = starts(words, length, ALPHABET[name])

    out = ['unit uWordStarts;\r\n\r\n',
           '// GENERATED by tools/make-wordstarts.py - do not edit.\r\n',
           '//\r\n',
           '// The first 3 and 4 letters of the words of the Russian (ru_RU,\r\n',
           '// Copyright (c) 1997-2008 Alexander I. Lebedev, BSD licence) and English\r\n',
           '// (en_US, SCOWL, Copyright 2000-2018 Kevin Atkinson) Hunspell dictionaries\r\n',
           '// of LibreOffice.  Each string is a run of fixed-length letter groups.\r\n\r\n',
           'interface\r\n\r\n',
           'const\r\n']
    for name, short in (('ru_RU', 'Ru'), ('en_US', 'En')):
        for length in (3, 4):
            out.append(pascal_array('%sStarts%d' % (short, length), sets[name, length]))
    out.append('\r\nimplementation\r\n\r\nend.\r\n')
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'uWordStarts.pas')
    with open(target, 'w', encoding='utf-8-sig', newline='') as f:
        f.write(''.join(out))
    for key, value in sets.items():
        print(key, len(value))


if __name__ == '__main__':
    main()
